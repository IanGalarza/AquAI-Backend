"""Puertos de persistencia con transacciones cortas e índice reconstruible."""
from __future__ import annotations
from contextlib import AbstractContextManager
from typing import Protocol
from uuid import UUID

from aquai.application.contracts.ingestion import PreparedTable
from aquai.application.contracts.retrieval import VerifiedDataset
from aquai.application.contracts.routing import CatalogDataset
from aquai.application.dtos.requests.listSources import SourceSort
from aquai.domain.models.source import Source


class SourceQueries(Protocol):
    def matching_datasets(self, reference: str) -> list[CatalogDataset]: ...
    def catalog_overview(self) -> list[dict]: ...
    def matching_column_values(self, dataset_id: UUID, version: int, column: str, value: str) -> list[str]: ...
    def find_text_values(self, datasets: list[VerifiedDataset], terms: list[str],
                         *, per_column: int = 50) -> dict[UUID, dict[str, list[dict]]]: ...
    def distinct_text_values(self, dataset: VerifiedDataset, columns: list[str],
                             *, limit: int = 500) -> dict[str, list[str]]: ...
    def list(self, *, page: int, page_size: int, search: str | None = None,
             processing_status: str | None = None, sort: SourceSort = SourceSort.NEWEST) -> dict: ...
    def get(self, source_id: UUID, *, include_content: bool = False) -> dict: ...
    def usable_dataset_ids(self, dataset_ids: list[UUID], *,
                           versions: dict[UUID, int] | None = None) -> set[UUID]: ...
    def verified_datasets(self, dataset_ids: list[UUID], *,
                          versions: dict[UUID, int] | None = None) -> list[VerifiedDataset]: ...


class SourceCommands(Protocol):
    def create_upload(self, source: Source) -> tuple[UUID, bool]: ...
    def worker_lock(self) -> AbstractContextManager[bool]: ...
    def claim_next(self) -> UUID | None: ...
    def recover_interrupted(self) -> int: ...
    def save_prepared(self, source_id: UUID, tables: list[PreparedTable], report: dict,
                      *, replace_existing: bool = False) -> None: ...
    def save_dataset_semantics(self, dataset_id: UUID, description: str, columns: list[dict],
                               warnings: list[str] | None = None) -> None: ...
    def set_index_status(self, source_id: UUID, status: str, error: str | None = None,
                         expected_active: bool | None = None) -> None: ...
    def claim_index_next(self) -> UUID | None: ...
    def set_active(self, source_id: UUID, active: bool) -> None: ...
    def record_failure(self, source_id: UUID, code: str, message: str) -> None: ...
    def request_reindex(self, source_id: UUID) -> None: ...
